"""Run every frozen failure injection against the SDK and the two cheap baselines; compare with EXPECTED.json.

Writes results/injections.json (machine) and results/injections.md (table). Exit 1 if any verifier departs from EXPECTED.
usage: python agent-receipts/run_injections.py"""
import json
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from agent_receipts import Signer, replay, verify  # noqa: E402
from agent_receipts import ed25519  # noqa: E402
from baselines import hash_chain, plain_log  # noqa: E402
from injections import injections as inj  # noqa: E402

EXPECTED = json.loads((HERE / "injections" / "EXPECTED.json").read_text(encoding="utf-8"))
# Departures from EXPECTED that were reviewed and explained in results/departures.md. Listed, not fixed: EXPECTED stays as
# frozen. Any departure not on this list fails the run.
REVIEWED = {("reorder", "hash_chain")}


def judge(exp: dict, got: dict) -> list:
    """Return the list of ways `got` departs from `exp`."""
    bad = []
    if got["passes"] != exp["passes"]:
        bad.append(f"passes={got['passes']} expected {exp['passes']}")
    missing = set(exp["detect"]) - set(got["codes"])
    if missing:
        bad.append(f"missing codes {sorted(missing)}")
    if exp.get("exact") and set(got["codes"]) != set(exp["detect"]):
        bad.append(f"codes {got['codes']} expected exactly {exp['detect']}")
    if "stale" in exp and got.get("stale") != exp["stale"]:
        bad.append(f"stale {got.get('stale')} expected {exp['stale']}")
    return bad


def main() -> int:
    t0 = time.perf_counter()
    real = Signer.from_seed(inj.SEED_REAL)
    rows, departures = [], 0
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        clean, other = td / "clean.jsonl", td / "other.jsonl"
        anchor = inj.build_clean(clean)
        inj.build_clean(other, session_meta={"task": "another session"})
        for name, case in EXPECTED["cases"].items():
            signed, repaired = td / f"{name}.signed.jsonl", td / f"{name}.repair.jsonl"
            inj.write_mutated(name, clean, other, signed, "signed")
            inj.write_mutated(name, clean, other, repaired, "repair")
            revoked = EXPECTED["revoked"] if case.get("revoke") else ()
            anc = anchor if case.get("anchor") else None
            rep = verify(signed, trusted={inj.ACTOR: real.public_hex}, anchor=anc, revoked=revoked)
            got = {
                "sdk": {"passes": rep.ok, "codes": sorted(rep.codes()), "stale": rep.stale,
                        "findings": [str(f) for f in rep.findings]},
                "hash_chain": hash_chain.verify(repaired, revoked=revoked, anchor=anc),
                "plain_log": plain_log.verify(repaired, revoked=revoked),
            }
            row = {"case": name, "attack": case["attack"], "got": got, "departures": {}}
            for v in ("sdk", "hash_chain", "plain_log"):
                d = judge(case[v], got[v])
                if d:
                    row["departures"][v] = d
                    departures += len(d)
            if "replay" in case:
                tools = dict(inj.TOOLS)
                for tool, impl in EXPECTED["replay_tools"].items():
                    tools[tool] = getattr(inj, impl)
                rr = replay(signed, tools)
                got["replay"] = rr.by_seq()
                if rr.by_seq() != case["replay"]:
                    row["departures"]["replay"] = [f"{rr.by_seq()} expected {case['replay']}"]
                    departures += 1
            rows.append(row)

    attacks = [r for r in rows if r["attack"]]
    score = {v: sum(not r["got"][v]["passes"] for r in attacks) for v in ("sdk", "hash_chain", "plain_log")}
    out = {
        "format": "agent-receipts-results/1",
        "python": sys.version.split()[0],
        "ed25519_backend": "cryptography" if ed25519.HAVE_CRYPTOGRAPHY else "pure-python",
        "wall_seconds": round(time.perf_counter() - t0, 3),
        "attacks": len(attacks),
        "detected": score,
        "departures_from_expected": departures,
        "cases": rows,
    }
    res = HERE / "results"
    res.mkdir(exist_ok=True)

    md = ["# Failure injections: results", "",
          f"Generated by `run_injections.py` (Python {out['python']}, Ed25519 backend: {out['ed25519_backend']}). "
          f"Expected verdicts were frozen before the implementation; departures from them: **{departures}**.", "",
          f"Attacks detected: SDK **{score['sdk']}/{len(attacks)}**, unsigned hash chain {score['hash_chain']}/{len(attacks)}, "
          f"plain JSONL log {score['plain_log']}/{len(attacks)}.", "",
          "| case | attack | SDK | hash chain | plain log |", "| --- | --- | --- | --- | --- |"]
    for r in rows:
        cell = lambda v: ("pass" if r["got"][v]["passes"] else "**FAIL**") + " " + ", ".join(
            c for c in r["got"][v]["codes"] if c != "ok")
        md.append(f"| {r['case']} | {'yes' if r['attack'] else 'no'} | {cell('sdk')} | {cell('hash_chain')} | "
                  f"{cell('plain_log')} |")
    md += ["", "For an attack, FAIL means the verifier caught it. `holder_rewrite` passing every verifier is the expected "
               "blind spot: whoever holds the signing key can rewrite history unless the close hash was published elsewhere "
               "(`holder_rewrite_with_anchor`)."]
    unreviewed = [(r["case"], v) for r in rows for v in r["departures"] if (r["case"], v) not in REVIEWED]
    out["unreviewed_departures"] = len(unreviewed)
    if any(r["departures"] for r in rows):
        md += ["", "## Departures from EXPECTED.json", "", "Reviewed ones are explained in [departures.md](departures.md).", ""]
        md += [f"- {r['case']} / {v}: {'; '.join(d)}" + (" (reviewed)" if (r["case"], v) in REVIEWED else " (NOT reviewed)")
               for r in rows for v, d in r["departures"].items()]
    (res / "injections.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8", newline="\n")
    (res / "injections.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(md))
    return 1 if unreviewed else 0


if __name__ == "__main__":
    sys.exit(main())
